# Extracts the functions that are MISSING from the live database into a single
# targeted migration, so applying it adds only what is absent instead of
# re-running the whole base schema.
#
#   powershell -ExecutionPolicy Bypass -File tools\extract_missing_rpcs.ps1
#
# ## Why
#
# A read-only probe of the live project (tools/probe_schema.ps1) reports which
# RPCs exist. The base schema 00021_full_schema.sql contains ALL of them, but
# applying that whole file to a database that already has 28 tables would
# redefine everything and re-run every policy - a large blast radius for what is
# actually a missing-function problem.
#
# This emits only the absent functions, so the change set is exactly the delta.
param(
    [string]$Source = "supabase\migrations\00021_full_schema.sql",
    [string]$Out = "supabase\migrations\0023_missing_rpcs.sql",
    [string[]]$Missing = @(
        'get_messages', 'get_messages_after', 'mark_read', 'mark_delivered',
        'get_or_create_direct_conversation', 'create_group_conversation',
        'set_reaction', 'normalize_phone', 'restore_profile_by_phone',
        'delete_user_account', 'register_device', 'set_presence',
        'submit_ban_appeal', 'validate_media_upload', 'device_link_qr_payload',
        'post_status', 'view_status', 'status_view_count',
        'admin_export_user_data'
    )
)

$ErrorActionPreference = "Stop"
$repo = Split-Path -Parent $PSScriptRoot
Set-Location $repo

$lines = Get-Content -LiteralPath $Source

function Get-FunctionBlock([string]$name) {
    $start = -1
    for ($i = 0; $i -lt $lines.Count; $i++) {
        if ($lines[$i] -match "^\s*create\s+or\s+replace\s+function\s+public\.$name\s*\(") {
            $start = $i
            break
        }
    }
    if ($start -lt 0) { return $null }

    # Walk forward tracking $$ depth so a semicolon inside a body does not end
    # the definition early.
    $depth = 0
    $body = New-Object System.Collections.ArrayList
    for ($i = $start; $i -lt $lines.Count; $i++) {
        [void]$body.Add($lines[$i])
        $depth += ([regex]::Matches($lines[$i], '\$\$')).Count
        if ($depth -gt 0 -and $lines[$i] -match '\$\$\s*;') { return ($body -join "`n") }
        if ($depth -eq 0 -and $i -gt $start -and $lines[$i] -match ';\s*$') { return ($body -join "`n") }
    }
    return ($body -join "`n")
}

function Get-GrantBlock([string]$name) {
    $grantLines = New-Object System.Collections.ArrayList
    for ($i = 0; $i -lt $lines.Count; $i++) {
        if ($lines[$i] -match "^\s*(grant|revoke)\s+.*\b$name\s*\(") {
            [void]$grantLines.Add($lines[$i])
        }
    }
    return ($grantLines -join "`n")
}

$header = @"
-- ===========================================================================
-- Crystal Messenger - migration 0023: RPCs missing from the live database
--
-- GENERATED by tools/extract_missing_rpcs.sql from $Source
--
-- ## Why this file exists
--
-- A read-only probe of the deployed project found that the database has all 28
-- tables but is missing most of the RPCs the Flutter client calls by name. The
-- app builds and boots, and login and the chat list work, because get_my_chats
-- exists - but these fail at RUNTIME, one action at a time, with a PostgREST
-- error the user never sees explained:
--
--   get_messages / get_messages_after   opening a chat loads nothing
--   get_or_create_direct_conversation   starting a new chat fails
--   create_group_conversation           no groups
--   mark_read / mark_delivered           read receipts dead
--   set_reaction                        reactions dead
--   register_device / set_presence      no device registration, no online status
--   delete_user_account                 Settings -> Delete account fails
--   restore_profile_by_phone            "I already have an account" fails
--   submit_ban_appeal                   appeals fail
--   post_status / view_status           Updates tab fails
--   device_link_qr_payload              device linking QR fails
--
-- Rather than re-applying the whole base schema - which would redefine 28
-- tables' worth of policies against a live database - this adds only what is
-- absent.
--
-- ## Idempotency
--
-- `create or replace function` throughout, so applying twice is a no-op. Grants
-- and revokes are repeated verbatim and are themselves idempotent.
--
-- ## Apply
--
--   begin;
--   \i 0023_missing_rpcs.sql
--   commit;
--
-- Then re-run supabase/migrations/PREFLIGHT.sql and confirm the MISSING count
-- for functions drops to 0.
-- ===========================================================================
"@

$sql = New-Object System.Collections.ArrayList
[void]$sql.Add($header)
[void]$sql.Add("")
[void]$sql.Add("set search_path = public;")
[void]$sql.Add("")
[void]$sql.Add("")

$found = @(); $absent = @()
foreach ($name in $Missing) {
    $block = Get-FunctionBlock $name
    if ($null -eq $block) {
        $absent += $name
        Write-Host "  ABSENT FROM SOURCE  $name  (not defined in $Source)" -ForegroundColor Yellow
        continue
    }
    $found += $name
    [void]$sql.Add("-- ---------------------------------------------------------------------------")
    [void]$sql.Add("-- $name")
    [void]$sql.Add("-- ---------------------------------------------------------------------------")
    [void]$sql.Add($block.TrimEnd())
    $grants = Get-GrantBlock $name
    if ($grants.Trim()) {
        [void]$sql.Add("")
        [void]$sql.Add($grants.Trim())
    }
    [void]$sql.Add("")
}

[void]$sql.Add("do $$")
[void]$sql.Add("begin")
[void]$sql.Add("  raise notice '0023 installed $($found.Count) RPC(s)'")
foreach ($n in $found) { [void]$sql.Add("  raise notice '  - $n'") }
[void]$sql.Add("end;")
[void]$sql.Add('$$;')
[void]$sql.Add("")

$dir = Split-Path -Parent $Out
if ($dir -and -not (Test-Path $dir)) { New-Item -ItemType Directory -Path $dir -Force | Out-Null }
[System.IO.File]::WriteAllLines($Out, $sql, (New-Object System.Text.UTF8Encoding($false)))

Write-Host ""
Write-Host "Extracted $($found.Count) function(s) to $Out"
if ($absent.Count) {
    Write-Host "NOT FOUND in source (need to be written by hand):" -ForegroundColor Yellow
    $absent | ForEach-Object { Write-Host "  $_" }
}