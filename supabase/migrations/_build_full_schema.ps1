# Builds 00021_full_schema.sql — the COMPLETE database in one file.
#
# Concatenates every migration in numeric order (00001..00020) with NOTHING
# removed, then rewrites the handful of statements that are not re-runnable so
# the single file can be applied to a fresh project OR an existing one that
# already has the individual migrations applied.
#
# Order is preserved exactly, because later migrations depend on objects the
# earlier ones create (e.g. 00015 flips the `attachments` bucket to private,
# which 00001 created as public).
#
# Note 00020: it adds the `devices` columns and the three RPCs the app calls
# that previously lived only in loose scripts outside the migration chain.
# Without it the app's profile query fails, and the router loops the user
# between /setup and / so the onboarding form's submit button looks inert.
#
# Run from the project root:
#   powershell -ExecutionPolicy Bypass -File supabase/migrations/_build_full_schema.ps1

$ErrorActionPreference = 'Stop'
$dir = Split-Path -Parent $MyInvocation.MyCommand.Path

# Every migration in numeric order. Discovered from disk rather than listed, so
# adding a migration is enough to have it included — a hard-coded list silently
# drops any file someone forgets to add, which is how the device columns and
# three RPCs came to be missing from the generated schema in the first place.
#
# The generated `*_full_schema.sql` output is excluded so it can never contain
# itself.
$migrations = @(
  Get-ChildItem -Path $dir -Filter '*.sql' |
    Where-Object { $_.Name -notlike '_*' } |
    Where-Object { $_.Name -notmatch '^\d{5}_full_schema\.sql$' } |
    Sort-Object Name
)
if ($migrations.Count -eq 0) { throw "no migrations found in $dir" }

$names = @($migrations | ForEach-Object { $_.Name })
if ($names.Count -eq 0) { throw 'migration list is empty after filtering' }

# Ordering is load-bearing: 00015 flips the `attachments` bucket to private,
# which only exists because 00001 created it. Sort numerically rather than
# trusting the filename sort.
$names = @($names | Sort-Object { [int]($_.Substring(0, 5)) })

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('-- ============================================================================')
[void]$sb.AppendLine('-- Crystal Messenger - COMPLETE DATABASE (single migration)')
[void]$sb.AppendLine('--')
[void]$sb.AppendLine("-- Generated by _build_full_schema.ps1 from $($names.Count) migrations:")
[void]$sb.AppendLine(($names | ForEach-Object { "--   $_" }) -join "`n")
[void]$sb.AppendLine('-- Nothing was removed: this is every migration, in order, concatenated.')
[void]$sb.AppendLine('--')
[void]$sb.AppendLine('-- Apply with `supabase db push`, or paste into the Supabase SQL editor.')
[void]$sb.AppendLine('-- It is safe to run more than once - statements that would fail on a')
[void]$sb.AppendLine('-- second run are wrapped in a guard. It is NOT destructive to user data:')
[void]$sb.AppendLine('-- no table is dropped and no message or profile is deleted.')
[void]$sb.AppendLine('--')
[void]$sb.AppendLine('-- If you are coming from the individual migrations and your live database')
[void]$sb.AppendLine('-- is already up to date, you can delete its rows from')
[void]$sb.AppendLine('-- supabase_migrations.schema_migrations afterwards; this file is the')
[void]$sb.AppendLine('-- authoritative record going forward.')
[void]$sb.AppendLine('-- ============================================================================')
[void]$sb.AppendLine('')

foreach ($name in $names) {
  $path = Join-Path $dir $name
  if (-not (Test-Path $path)) { throw "missing migration: $name" }

  [void]$sb.AppendLine('')
  [void]$sb.AppendLine('-- ############################################################################')
  [void]$sb.AppendLine("-- $name")
  [void]$sb.AppendLine('-- ############################################################################')
  [void]$sb.AppendLine('')

  # Read as UTF-8 so the em-dashes and box characters in the original headers
  # survive; Set-Content defaults to ANSI on Windows and mangles them.
  $text = [System.IO.File]::ReadAllText($path, [System.Text.Encoding]::UTF8)
  [void]$sb.AppendLine($text)
}

$content = $sb.ToString()

# ---------------------------------------------------------------------------
# Rewrite 1: `create type public.chat_summary` is not `if not exists`-able in
# PostgreSQL, and it is also already created by 00001. Wrap the whole statement
# in a catalog check so a second run is a no-op.
# ---------------------------------------------------------------------------
$typeBody = [regex]::Match(
  $content,
  '(?s)create type public\.chat_summary as \(.*?^\);',
  [System.Text.RegularExpressions.RegexOptions]::Multiline
)
if (-not $typeBody.Success) { throw 'chat_summary type definition not found' }

$inner = $typeBody.Value -replace '(?m)^', '    '
$typeGuarded = @'
do $$
begin
  if not exists (
    select 1
      from pg_type t
      join pg_namespace n on n.oid = t.typnamespace
     where n.nspname = 'public' and t.typname = 'chat_summary'
  ) then
__BODY__
  end if;
end;
$$;
'@
$typeGuarded = $typeGuarded.Replace('__BODY__', $inner).TrimEnd()
$content = $content.Replace($typeBody.Value, $typeGuarded)

# ---------------------------------------------------------------------------
# Rewrite 2: `alter type ... add attribute` has no `if not exists` in
# PostgreSQL, and these same three attributes are added by both 00012 and
# 00013. Guard each one by looking it up in pg_attribute.
# ---------------------------------------------------------------------------
$addAttr = [regex]'alter type public\.chat_summary add attribute (\w+) ([^;]+);'
$addAttrTemplate = @'
do $$
begin
  if not exists (
    select 1
      from pg_attribute a
      join pg_type t on t.typid = a.attrelid
      join pg_namespace n on n.oid = t.typnamespace
     where n.nspname = 'public'
       and t.typname = 'chat_summary'
       and a.attname = '__NAME__'
       and not a.attisdropped
  ) then
    alter type public.chat_summary add attribute __NAME__ __TYPE__;
  end if;
end;
$$;
'@
$content = $addAttr.Replace($content, {
  param($m)
  $name = $m.Groups[1].Value
  $type = $m.Groups[2].Value.Trim()
  $script:addAttrTemplate.Replace('__NAME__', $name).Replace('__TYPE__', $type).TrimEnd()
})

# ---------------------------------------------------------------------------
# Rewrite 3: `create policy` fails when the policy already exists, and several
# names are defined by more than one migration (profiles_select x2,
# messages_insert x3, groups_select x3). Drop first so the last definition wins.
#
# `create trigger` has the same problem, and its target table is often on the
# next line ("before insert on public.x"), so the table is read from either.
# ---------------------------------------------------------------------------
$lines = $content -split "`r?`n"
$out = New-Object System.Text.StringBuilder
$prevDrop = ''

for ($i = 0; $i -lt $lines.Length; $i++) {
  $line = $lines[$i]

  if ($line -match '^\s*create policy\s+"([^"]+)"\s+on\s+([\w\.]+)') {
    $drop = "drop policy if exists `"$($matches[1])`" on $($matches[2]);"
    if ($prevDrop -ne $drop) { [void]$out.AppendLine($drop); $prevDrop = $drop }
  }
  elseif ($line -match '^\s*create trigger\s+(\S+)') {
    $trigger = $matches[1]
    $on = $null
    if ($line -match '\bon\s+([\w\.]+)') {
      $on = $matches[1]
    }
    elseif (($i + 1) -lt $lines.Length -and $lines[$i + 1] -match '\bon\s+([\w\.]+)') {
      $on = $matches[1]
    }
    if ($on) {
      $drop = "drop trigger if exists $trigger on $on;"
      if ($prevDrop -ne $drop) { [void]$out.AppendLine($drop); $prevDrop = $drop }
    }
  }
  else {
    $prevDrop = ''
  }

  [void]$out.AppendLine($line)
}
$content = $out.ToString()

# ---------------------------------------------------------------------------
# Rewrite 4: `alter publication ... add table` errors on a table that is
# already in the publication. Every one of these lives inside a function or a
# DO block already (verified), so no rewrite is needed — but assert it rather
# than trust it, because a bare one would break every re-run.
# ---------------------------------------------------------------------------
$bare = [regex]::Matches(
  $content,
  '(?m)^\s*alter publication\b'
)
foreach ($m in $bare) {
  # A `alter publication` at the start of a line, directly inside a
  # `do $$`/`end`/`exception` block, is fine. Count the `$$` markers that
  # precede it: an odd number means it is inside a block, an even number means
  # it is top level and therefore unsafe.
  $before = $content.Substring(0, $m.Index)
  $markers = ([regex]::Matches($before, '\$\$')).Count
  if ($markers % 2 -eq 0) {
    throw "top-level 'alter publication' found at offset $($m.Index) - it will fail on re-run"
  }
}

# ---------------------------------------------------------------------------
# Rewrite 5: a function whose RETURN TYPE changed between migrations.
#
# PostgreSQL refuses `create or replace function` when the new return type
# differs from the installed one (42P13 "cannot change return type of existing
# function"). Two real cases in this chain:
#
#   00001  get_messages(...)        returns setof public.messages
#   00012  get_messages(...)        returns table (id uuid, client_message_id ...)
#   00013  get_messages(...)        returns table (id uuid, ...)     -- same
#   00001  get_messages_after(...)  returns setof public.messages
#   00012  get_messages_after(...)  returns table (id uuid, ...)
#
# So a database that already has the 00001 version cannot be upgraded by
# replaying the chain — the very thing this single file is for. For every
# function definition, compare the declared return type against pg_proc and
# drop first when the two disagree.
#
# `pg_get_function_result` renders `returns table (...)` as `TABLE(id uuid,
# ...)`, so both sides go through the same normaliser before comparing.
# ---------------------------------------------------------------------------

# Collapses a declared return type to the shape pg_get_function_result emits.
function Normalize-ReturnType([string] $text) {
  if ($null -eq $text) { return '' }
  $t = $text.Trim().ToLower()
  $t = $t -replace '\s+', ' '
  $t = $t -replace '^returns\s+', ''
  $t = $t -replace '\s*\(', '('
  $t = $t -replace '\s*\)', ')'
  $t = $t -replace ',\s*', ', '
  $t = $t -replace '\s+', ' '
  return $t.Trim()
}

# Reads `name(arg types)` and the declared return type starting at the
# `create or replace function` line at index $start.
function Read-FunctionHeader([string[]] $lines, [int] $start) {
  $name = $null
  for ($i = $start; $i -lt $lines.Length; $i++) {
    $line = $lines[$i]
    if ($null -eq $name) {
      if ($line -match 'create or replace function\s+(?:public\.)?(\w+)\s*\(') {
        $name = $matches[1]
      } else {
        continue
      }
    }

    # Collect the parenthesised argument list, which may span lines and may
    # contain nested parens in a default expression.
    $open = $line.IndexOf('(')
    if ($open -lt 0) { continue }
    $buf = ''
    $depth = 0
    $j = $i
    for (; $j -lt $lines.Length; $j++) {
      foreach ($ch in $lines[$j].ToCharArray()) {
        if ($ch -eq '(') { $depth++ } elseif ($ch -eq ')') { $depth-- }
      }
      $buf += $lines[$j]
      if ($depth -le 0) { break }
    }
    $args = $buf.Substring($buf.IndexOf('(') + 1, $buf.LastIndexOf(')') - $buf.IndexOf('(') - 1)
    $tail = $buf.Substring($buf.LastIndexOf(')') + 1)

    # Scan forward for the `returns` clause, which sits among the options.
    $opts = $tail
    for ($k = $j + 1; $k -lt $lines.Length; $k++) {
      $opts += ' ' + $lines[$k].Trim()
      if ($opts -match '(?i)returns\s+(table\s*\(.*?\)|setof\s+[\w\.\[\]]+|[\w\.\[\]]+)\s*(?:language\b|security\b|as\b|$)') { break }
    }
    if ($opts -notmatch '(?i)returns\s+(table\s*\(.*?\)|setof\s+[\w\.\[\]]+|[\w\.\[\]]+)\s*(?:language\b|security\b|as\b|$)') {
      return $null
    }

    return [pscustomobject]@{
      Name   = $name
      Args   = ($args -replace 'default\s+[^,)]*', '' -replace '\s+', ' ').Trim()
      Return = $matches[1]
    }
  }
  return $null
}

$flines = $content -split "`r?`n"
$guarded = New-Object System.Text.StringBuilder
$guardedCount = 0
for ($i = 0; $i -lt $flines.Length; $i++) {
  if ($flines[$i] -match '^\s*create or replace function\s') {
    $header = Read-FunctionHeader $flines $i
    if ($null -ne $header) {
      $want = (Normalize-ReturnType $header.Return).Replace("'", "''")
      # Identity arguments are the type of each parameter, in order, with any
      # default expression stripped. `pg_get_function_identity_arguments`
      # renders exactly this form for functions that have no OUT params.
      $argTypes = @()
      foreach ($a in ($header.Args -split ',' | Where-Object { $_.Trim() })) {
        $parts = $a.Trim() -split '\s+'
        if ($parts.Count -ge 2) { $argTypes += $parts[-1] }
      }
      $sig = 'public.' + $header.Name + '(' + ($argTypes -join ',') + ')'
      $identArgs = ($argTypes -join ',').Replace("'", "''")

      [void]$guarded.AppendLine('do $$')
      [void]$guarded.AppendLine('begin')
      [void]$guarded.AppendLine('  -- 42P13 guard: PostgreSQL cannot change a function''s return type')
      [void]$guarded.AppendLine('  -- in place, so drop it when the installed version differs.')
      [void]$guarded.AppendLine('  if exists (')
      [void]$guarded.AppendLine('    select 1')
      [void]$guarded.AppendLine('      from pg_proc p')
      [void]$guarded.AppendLine('      join pg_namespace n on n.oid = p.pronamespace')
      [void]$guarded.AppendLine("     where n.nspname = 'public'")
      [void]$guarded.AppendLine("       and p.proname = '$($header.Name)'")
      [void]$guarded.AppendLine("       and pg_get_function_identity_arguments(p.oid) = '$identArgs'")
      [void]$guarded.AppendLine("       and pg_get_function_result(p.oid) <> '$want'")
      [void]$guarded.AppendLine('  ) then')
      [void]$guarded.AppendLine("    drop function if exists $sig;")
      [void]$guarded.AppendLine('  end if;')
      [void]$guarded.AppendLine('end;')
      [void]$guarded.AppendLine('$$;')
      [void]$guarded.AppendLine('')
      $guardedCount++
    }
  }
  [void]$guarded.AppendLine($flines[$i])
}
$content = $guarded.ToString()

$target = Join-Path $dir '00021_full_schema.sql'
[System.IO.File]::WriteAllText($target, $content, (New-Object System.Text.UTF8Encoding($false)))

Write-Output ("Wrote " + (Resolve-Path $target).Path)
Write-Output ("Lines: " + ($content -split "`r?`n").Length)
Write-Output ("Size:  " + [math]::Round((Get-Item $target).Length / 1KB, 1) + " KB")
Write-Output ''
Write-Output 'Verification:'
Write-Output ("  migrations merged : " + $names.Count)
Write-Output ("  return-type guards: " + $guardedCount)
# Fail the build if a function the app calls at runtime is absent: a missing
# RPC surfaces to the user as a button that does nothing, which is exactly the
# class of bug this merge is meant to prevent.
$required = @(
  'register_device', 'delete_user_account', 'normalize_phone',
  'restore_profile_by_phone', 'get_my_chats', 'get_messages',
  'get_messages_after', 'set_reaction', 'create_group_conversation',
  'get_or_create_direct_conversation', 'ensure_user_settings', 'set_presence',
  'get_ban_status', 'purge_stale_media_uploads', 'media_storage_usage',
  'handle_new_user'
)
$absent = @()
foreach ($fn in $required) {
  if ($content -notmatch "function public\.$fn\b") { $absent += $fn }
}
if ($absent.Count -gt 0) {
  throw ("merged file is missing RPCs the app calls: " + ($absent -join ', '))
}
foreach ($col in @('device_model', 'device_os', 'device_manufacturer',
                   'device_locale', 'app_version', 'is_current_device')) {
  if ($content -notmatch "add column if not exists $col\b") {
    throw "merged file is missing devices.$col (the app's profile query embeds it)"
  }
}
Write-Output "  required RPCs    : all present"
Write-Output ("  create policy      : " + ([regex]::Matches($content, '(?m)^\s*create policy')).Count)
Write-Output ("  drop policy guards : " + ([regex]::Matches($content, '(?m)^drop policy if exists')).Count)
Write-Output ("  create trigger     : " + ([regex]::Matches($content, '(?m)^\s*create trigger')).Count)
Write-Output ("  drop trigger guards: " + ([regex]::Matches($content, '(?m)^drop trigger if exists')).Count)
Write-Output ("  bare create type   : " + ([regex]::Matches($content, '(?m)^create type')).Count)
Write-Output ("  add attribute      : " + ([regex]::Matches($content, 'add attribute')).Count)
